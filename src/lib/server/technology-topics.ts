/** Subtemas de una tecnología (`[]` si no tiene). */
export function topicsFor(technologyId: string): string[] {
  return TECHNOLOGY_TOPICS[technologyId.trim().toLowerCase()] ?? [];
}

/**
 * Porción de subtemas para una llamada al generador. Cada tipo de pregunta (`callIndex`) arranca
 * en un punto distinto de la lista, así las 5 llamadas de una tecnología cubren todos los subtemas
 * en vez de repetir los primeros.
 */
export function topicsForCall(topics: string[], callIndex: number, count: number): string[] {
  if (topics.length === 0 || count <= 0) return [];
  const out: string[] = [];
  const start = (callIndex * count) % topics.length;
  for (let i = 0; i < count; i++) out.push(topics[(start + i) % topics.length]);
  return out;
}
